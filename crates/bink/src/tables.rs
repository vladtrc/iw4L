const QUANT_SCALE: [(i64, i64); 16] = [
    (1, 1),
    (4, 3),
    (5, 3),
    (2, 1),
    (8, 3),
    (7, 2),
    (4, 1),
    (5, 1),
    (6, 1),
    (8, 1),
    (12, 1),
    (17, 1),
    (22, 1),
    (28, 1),
    (34, 1),
    (44, 1),
];

const fn quant_matrices(base: &[i32; 64], fix: &[[i8; 64]; 16]) -> [[i32; 64]; 16] {
    let mut out = [[0; 64]; 16];
    let mut q = 0;
    while q < 16 {
        let (num, den) = QUANT_SCALE[q];
        let mut i = 0;
        while i < 64 {
            let scaled = (base[i] as i64 * num * 2 + den) / (2 * den);
            out[q][i] = scaled as i32 + fix[q][i] as i32;
            i += 1;
        }
        q += 1;
    }
    out
}
