pub fn reference_code_constant_index(name: &str) -> Option<u16> {
    REFERENCE_CODE_CONSTANTS
        .iter()
        .find(|(known, _)| *known == name)
        .map(|(_, index)| *index)
}

pub fn reference_code_texture_index(name: &str) -> Option<u32> {
    REFERENCE_CODE_TEXTURES
        .iter()
        .find(|(known, _)| *known == name)
        .map(|(_, index)| u32::from(*index))
}
