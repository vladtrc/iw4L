pub fn route(voice: &str, line: &str) -> String {
    let (hardcore, mut line) = line
        .strip_prefix("hc_")
        .map_or((false, line), |line| (true, line));
    for prefix in ["dfcn_", "dh_", "tctl_", "thirdp_"] {
        line = line.strip_prefix(prefix).unwrap_or(line);
    }
    let line = line.strip_suffix("_pro").unwrap_or(line);
    let line = LINES
        .iter()
        .find(|(from, _)| *from == line)
        .map_or(line, |(_, to)| *to);
    format!("{voice}{}{line}", if hardcore { "hc" } else { "" })
}
